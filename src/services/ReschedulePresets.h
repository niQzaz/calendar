#pragma once

#include <QDate>
#include <QDateTime>
#include <QTime>

// Этап C - быстрые варианты переноса задачи ("через 15 минут", "завтра"...).
//
// Это ЧИСТАЯ логика без UI и БД (только QtCore): по исходному слоту вхождения
// и текущему моменту считает, куда именно перенести. Вынесена из диалога,
// чтобы границы (полночь, округление) можно было проверить юнит-тестами -
// сам диалог автоматическими тестами не покрыт.
//
// Общие правила:
//  - длительность сохраняется (конец = начало + исходная длительность);
//  - вхождение не может переходить через полночь (у события одна дата и два
//    времени), поэтому конец должен быть не позже 23:59;
//  - если пресет не помещается - он НЕВАЛИДЕН (valid == false) и UI его
//    отключает; время молча не обрезается.
enum class ReschedulePreset
{
    In15Min,    // now + 15 минут, начало округляется вверх до 5 минут
    In30Min,    // now + 30 минут, то же округление
    InOneHour,  // now + 60 минут, то же округление
    LaterToday, // now + 2 часа, округляется вверх до полного часа
    Tomorrow    // завтра (относительно now.date()), то же время начала/конца
};

struct RescheduleTarget
{
    bool valid = false;
    QDate date;
    QTime start;
    QTime end;
};

// origStart/origEnd - время вхождения (для повторяющегося события - время
// шаблона, у всех его вхождений оно одинаково). now - текущий момент (явный
// параметр, чтобы результат не зависел от часов машины в тестах).
//
// Секунды в origStart/origEnd не учитываются (события хранятся с точностью
// до минуты). Округление "вверх" означает: ровно на границе (с нулевыми
// секундами) значение остаётся, любое превышение уходит на следующую границу.
RescheduleTarget computePresetTarget(ReschedulePreset preset,
                                     const QTime &origStart,
                                     const QTime &origEnd,
                                     const QDateTime &now);
