#pragma once

#include <QString>
#include <QDate>
#include <QTime>

// Тип повторения события.
// Хранится в БД одной строкой (без физического дублирования на каждую
// дату) - конкретные даты, на которые событие выпадает, вычисляются
// функцией eventOccursOnDate() ниже, а не хранятся отдельно.
enum class RecurrenceType
{
    None,       // обычное разовое событие
    Daily,      // каждый день, начиная с Event::date
    Weekdays,   // только по будням (Пн-Пт)
    Weekly,     // раз в неделю, в тот же день недели, что и Event::date
    Custom      // каждые recurrenceInterval дней, начиная с Event::date
};

// Событие расписания: название, дата, время начала/окончания, описание.
//
// Это просто структура данных (POD-like), без какой-либо логики внутри,
// кроме свободных функций ниже, которые оперируют её данными. Вся логика
// работы с коллекцией событий (добавление, удаление, поиск) находится
// в EventManager.
//
// Для повторяющегося события (recurrenceType != None) поле date - это
// дата ПЕРВОГО повторения ("якорь"), а не единственная дата события.
struct Event
{
    int id = -1;   // уникальный идентификатор, назначается EventManager'ом
                   // (-1 означает "id ещё не присвоен")
    QString title;
    QDate date;
    QTime startTime;
    QTime endTime;
    QString description;

    // Сколько рабочих отрезков Pomodoro было завершено для этого события.
    // Для повторяющегося события счётчик общий на всю серию, а не на
    // конкретное повторение - усложнять до поштучного учёта не требуется.
    int pomodorosCompleted = 0;

    RecurrenceType recurrenceType = RecurrenceType::None;
    int recurrenceInterval = 1;   // используется только при RecurrenceType::Custom
    QDate recurrenceEndDate;      // невалидная (по умолчанию) дата = без окончания

    // Добавлено для импорта недельного расписания из внешнего формата
    // (TYPE/CONTENT/.../DURATION_UNIT). Только хранение - никакой сложной
    // логики конвертации часовых поясов или сортировки по приоритету
    // сейчас нет, как и попросили: главное - не терять эти данные.
    int priority = 0;      // 0 = не указан/не важен; чем меньше число, тем
                            // важнее задача (так было в исходном CSV: 1 - высший)
    QString timezone;      // например "Europe/Moscow"; пусто = не указан

    // Категория (MVP2). categoryId - единственное, что реально хранится
    // в таблице events (внешний ключ на categories.id; -1 = без категории).
    // categoryName/categoryColor НЕ хранятся в events - EventManager
    // подставляет их через LEFT JOIN с categories при чтении, только
    // для удобства отображения в UI. Не пишите их напрямую при создании
    // Event для addEvent()/updateEvent() - они игнорируются, источник
    // истины для цвета/имени - таблица categories.
    int categoryId = -1;
    QString categoryName;
    QString categoryColor;
};

// Отвечает на вопрос "выпадает ли это событие (обычное или повторяющееся)
// на указанную дату?". Чистая функция без обращения к БД - именно
// благодаря ей EventManager не хранит по строке на каждое повторение.
bool eventOccursOnDate(const Event &event, const QDate &date);

// Короткое человекочитаемое описание правила повтора для отображения
// в UI (например, "Repeats weekly"). Пустая строка для обычных событий.
QString recurrenceSummary(const Event &event);

