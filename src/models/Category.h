#pragma once

#include <QString>

// Категория события: имя + цвет. Хранится в отдельной таблице categories -
// цвет управляется централизованно (поменял цвет категории - поменялись
// сразу все события этой категории), а не хранится на каждом событии
// по отдельности.
//
// Как и Event, это просто структура данных - вся логика (CRUD, разрешение
// event.categoryId в имя/цвет через JOIN) находится в EventManager.
struct Category
{
    int id = -1;    // -1 = категория ещё не сохранена в БД
    QString name;
    QString color;  // hex-строка, например "#4A90D9"
};
