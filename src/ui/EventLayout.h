#pragma once

#include "models/Event.h"

#include <QVector>

// Результат раскладки одного события внутри дня: на какую "дорожку"
// (0-based) оно попало и сколько всего дорожек используется в его
// пересекающейся группе - вместе это даёт горизонтальную позицию и ширину
// прямоугольника события в TimeGridView.
struct EventLayoutSlot
{
    Event event;
    int laneIndex = 0;
    int laneCount = 1;
};

// Раскладывает события одного дня так, чтобы пересекающиеся по времени
// события не перекрывали друг друга полностью, а вставали рядом
// (как в задании: не сложнейший алгоритм Google Calendar, а простая
// раскладка "в дорожки", которой достаточно для читаемости).
//
// Идея: сортируем по времени начала, сканируем слева направо, для каждого
// события ищем первую дорожку, чьё последнее событие уже закончилось
// к моменту начала текущего - если такой нет, открываем новую дорожку.
// События группируются во "кластеры" непрерывно пересекающихся друг
// с другом событий - у всех событий одного кластера laneCount одинаковый
// (число дорожек, понадобившихся именно этому кластеру), а не общий
// максимум по всему дню - иначе несвязанные события "сузились" бы
// из-за дорожек, занятых совсем другими, не пересекающимися с ними
// событиями в тот же день.
QVector<EventLayoutSlot> layoutEventsForDay(const QVector<Event> &events);
