#pragma once

#include <QString>

// Общий интерфейс представлений календаря (Month/Week/Day).
//
// CalendarView (контейнер с общей шапкой навигации) не должен знать,
// работает ли он сейчас с месяцем, неделей или днём - ему достаточно
// уметь попросить "предыдущий период"/"следующий период"/"сегодня"
// и получить текст заголовка. MonthView/WeekView/DayView реализуют
// это каждый по-своему (у месяца - предыдущий месяц, у недели -
// предыдущая неделя и т.д.), но снаружи выглядят одинаково.
//
// Не QObject: это чистый интерфейс без сигналов/слотов, реализующие
// классы дополнительно наследуют QWidget - стандартный и безопасный
// в Qt способ добавить виджету интерфейс, не переусложняя иерархию.
class ICalendarPage
{
public:
    virtual ~ICalendarPage() = default;

    virtual void goToPrevious() = 0;
    virtual void goToNext() = 0;
    virtual void goToToday() = 0;

    // Текст заголовка периода: "September 2026" для месяца,
    // "14 - 20 September 2026" для недели, "Wednesday, 16 September 2026" для дня.
    virtual QString headerTitle() const = 0;
};
